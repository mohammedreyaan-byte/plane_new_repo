/* eslint-disable @typescript-eslint/no-explicit-any */
import type { AxiosInstance, AxiosRequestConfig } from "axios";
import { create } from "axios";
import { TOAST_TYPE, setToast } from "@plane/propel/toast";

// Error codes of the workflow engine. These carry a message written for the person who tried the move.
const WORKFLOW_ERROR_CODES = new Set([
  "transition_forbidden",
  "transition_not_allowed",
  "state_not_in_workflow",
  "comment_required",
  "fields_required",
  "epic_has_open_children",
  "invalid_parent_type",
  "types_disabled",
  "type_not_enabled",
  "workflow_unavailable",
  "wip_limit_reached",
]);

export abstract class APIService {
  protected baseURL: string;
  private axiosInstance: AxiosInstance;

  constructor(baseURL: string) {
    this.baseURL = baseURL;
    this.axiosInstance = create({
      baseURL,
      withCredentials: true,
    });

    this.setupInterceptors();
  }

  private setupInterceptors() {
    this.axiosInstance.interceptors.response.use(
      (response) => response,
      (error) => {
        if (error.response && error.response.status === 401) {
          const currentPath = window.location.pathname;
          window.location.replace(`/${currentPath ? `?next_path=${currentPath}` : ``}`);
        }
        const body = error?.response?.data?.error;
        if (body && typeof body === "object" && WORKFLOW_ERROR_CODES.has(body.code) && body.message) {
          setToast({ type: TOAST_TYPE.ERROR, title: "Action not allowed", message: body.message });
        }
        return Promise.reject(error);
      }
    );
  }

  get(url: string, params = {}, config: AxiosRequestConfig = {}) {
    return this.axiosInstance.get(url, {
      ...params,
      ...config,
    });
  }

  post(url: string, data = {}, config: AxiosRequestConfig = {}) {
    return this.axiosInstance.post(url, data, config);
  }

  put(url: string, data = {}, config: AxiosRequestConfig = {}) {
    return this.axiosInstance.put(url, data, config);
  }

  patch(url: string, data = {}, config: AxiosRequestConfig = {}) {
    return this.axiosInstance.patch(url, data, config);
  }

  delete(url: string, data?: any, config: AxiosRequestConfig = {}) {
    return this.axiosInstance.delete(url, { data, ...config });
  }

  request(config = {}) {
    return this.axiosInstance(config);
  }
}
