// Usage: npx tsx packages/i18n/scripts/generate-types.ts
// Reads: src/locales/en/*.json and src/locales/<locale>/*.json
// Writes: src/types/keys.generated.ts and src/core/locale-loaders.generated.ts

import fs from "node:fs";
import path from "node:path";

const COPYRIGHT_HEADER = `/**
 * Copyright (c) 2023-present Plane Software, Inc. and contributors
 * SPDX-License-Identifier: AGPL-3.0-only
 * See the LICENSE file for details.
 */`;

type NestedObject = { [key: string]: string | NestedObject };

// These four ARIA labels are intentionally duplicated in accessibility.json and
// common.json: they resolve from the default "common" namespace for components
// using useTranslation() without a namespace, and remain available to consumers
// of the accessibility namespace. Do not treat them as accidental collisions.
const ALLOWED_COLLISIONS = new Set([
  "aria_labels.app_sidebar.open_workspace_menu",
  "aria_labels.app_sidebar.close_workspace_menu",
  "aria_labels.app_sidebar.open_extended_sidebar",
  "aria_labels.app_sidebar.close_extended_sidebar",
]);

/**
 * Recursively flatten a nested object into dot-notated keys.
 * Returns an array of flattened key strings.
 */
function flattenKeys(obj: NestedObject, prefix = ""): string[] {
  const keys: string[] = [];

  for (const [key, value] of Object.entries(obj)) {
    const fullKey = prefix ? `${prefix}.${key}` : key;

    if (typeof value === "string") {
      keys.push(fullKey);
    } else if (typeof value === "object" && value !== null) {
      keys.push(...flattenKeys(value as NestedObject, fullKey));
    }
  }

  return keys;
}

/**
 * Detect path conflicts where a key is both a leaf (string value) and a prefix
 * of another key. For example, "workspace" as a leaf and "workspace.settings" as
 * another key would be a conflict.
 */
function detectPathConflicts(keys: string[]): string[] {
  // Build a set of all prefixes used across keys
  const prefixes = new Set<string>();
  for (const key of keys) {
    const parts = key.split(".");
    for (let i = 1; i < parts.length; i++) {
      prefixes.add(parts.slice(0, i).join("."));
    }
  }

  // A conflict exists when a leaf key is also a prefix
  const conflicts: string[] = [];
  for (const key of keys) {
    if (prefixes.has(key)) {
      const extending = keys.find((k) => k.startsWith(key + "."));
      if (extending) {
        conflicts.push(`Path conflict: "${key}" is both a leaf key and a prefix of "${extending}"`);
      }
    }
  }

  return conflicts;
}

/**
 * Generate literal dynamic imports for non-English locale resources.
 *
 * Vite cannot statically analyse `import(`../locales/${language}/${namespace}.json`)`
 * from the built package, so those resources were never emitted as browser chunks.
 * Literal imports keep non-English bundles lazy while making them discoverable.
 */
function generateLocaleLoaders(localesRootDir: string, outputDir: string): number {
  const formatKey = (value: string) => (/^[A-Za-z_$][\w$]*$/.test(value) ? value : JSON.stringify(value));
  const localeDirs = fs
    .readdirSync(localesRootDir, { withFileTypes: true })
    .filter((entry) => entry.isDirectory() && entry.name !== "en")
    .map((entry) => entry.name)
    .toSorted();
  const lines: string[] = [
    COPYRIGHT_HEADER,
    "",
    "// AUTO-GENERATED — DO NOT EDIT",
    "// Generated by packages/i18n/scripts/generate-types.ts.",
    'import type { ResourceKey } from "i18next";',
    "",
    "type LocaleLoader = () => Promise<ResourceKey>;",
    "",
    "const localeLoaders: Record<string, Record<string, LocaleLoader>> = {",
  ];
  let loaderCount = 0;

  for (const locale of localeDirs) {
    const localeDir = path.join(localesRootDir, locale);
    const namespaceNames = fs
      .readdirSync(localeDir)
      .filter((file) => file.endsWith(".json"))
      .map((file) => file.replace(/\.json$/, ""))
      .toSorted();

    if (namespaceNames.length === 0) continue;

    lines.push(`  ${formatKey(locale)}: {`);
    for (const namespace of namespaceNames) {
      lines.push(
        `    ${formatKey(namespace)}: () => import(${JSON.stringify(`../locales/${locale}/${namespace}.json`)}),`
      );
      loaderCount += 1;
    }
    lines.push("  },");
  }

  lines.push(
    "};",
    "",
    "export function loadLocaleResource(language: string, namespace: string): Promise<ResourceKey | null> {",
    "  const loader = localeLoaders[language]?.[namespace];",
    "  return loader ? loader() : Promise.resolve(null);",
    "}",
    ""
  );

  fs.writeFileSync(path.join(outputDir, "locale-loaders.generated.ts"), lines.join("\n"), "utf-8");
  return loaderCount;
}

function main(): void {
  const rootDir = import.meta.dirname;
  const localesRootDir = path.resolve(rootDir, "..", "src", "locales");
  const localesDir = path.join(localesRootDir, "en");
  const outputDir = path.resolve(rootDir, "..", "src", "types");
  const outputFile = path.join(outputDir, "keys.generated.ts");

  // Read all JSON files from the English locales directory
  if (!fs.existsSync(localesDir)) {
    console.error(`Error: Locales directory not found: ${localesDir}`);
    process.exit(1);
  }

  const jsonFiles = fs
    .readdirSync(localesDir)
    .filter((file) => file.endsWith(".json"))
    .sort();

  if (jsonFiles.length === 0) {
    console.error(`Error: No JSON files found in ${localesDir}`);
    process.exit(1);
  }

  // Track keys per namespace file for collision detection
  const keysByFile = new Map<string, string[]>();
  const allKeys = new Set<string>();
  const collisions: string[] = [];

  for (const file of jsonFiles) {
    const filePath = path.join(localesDir, file);
    const content = fs.readFileSync(filePath, "utf-8");
    const parsed = (() => {
      try {
        return JSON.parse(content) as NestedObject;
      } catch {
        console.error(`Error: Failed to parse JSON in ${file}`);
        process.exit(1);
      }
    })();

    const fileKeys = flattenKeys(parsed);
    keysByFile.set(file, fileKeys);

    // Detect cross-namespace collisions
    for (const key of fileKeys) {
      if (allKeys.has(key)) {
        // Find which file already had this key
        for (const [otherFile, otherKeys] of keysByFile.entries()) {
          if (otherFile !== file && otherKeys.includes(key) && !ALLOWED_COLLISIONS.has(key)) {
            collisions.push(`Cross-namespace collision: key "${key}" exists in both "${otherFile}" and "${file}"`);
          }
        }
      }
      allKeys.add(key);
    }
  }

  if (collisions.length > 0) {
    console.error("Error: Cross-namespace key collisions detected:");
    for (const collision of collisions) {
      console.error(`  ${collision}`);
    }
    process.exit(1);
  }

  // Detect path conflicts
  const sortedKeys = [...allKeys].sort();
  const pathConflicts = detectPathConflicts(sortedKeys);

  if (pathConflicts.length > 0) {
    console.error("Error: Path conflicts detected:");
    for (const conflict of pathConflicts) {
      console.error(`  ${conflict}`);
    }
    process.exit(1);
  }

  // Ensure output directory exists
  if (!fs.existsSync(outputDir)) {
    fs.mkdirSync(outputDir, { recursive: true });
  }

  // Generate the output file
  const keyLines = sortedKeys.map((key) => `  | "${key}"`).join("\n");
  const output = `${COPYRIGHT_HEADER}

// AUTO-GENERATED — DO NOT EDIT
// Generated from ${jsonFiles.length} English namespace files (${sortedKeys.length} keys)
// Run: pnpm run generate:types

export type TTranslationKeys =
${keyLines}
  ;
`;

  fs.writeFileSync(outputFile, output, "utf-8");

  const loaderCount = generateLocaleLoaders(localesRootDir, path.resolve(rootDir, "..", "src", "core"));
  console.log(`Generated ${sortedKeys.length} keys from ${jsonFiles.length} namespace files`);
  console.log(`Generated ${loaderCount} lazy locale loaders`);
}

main();
